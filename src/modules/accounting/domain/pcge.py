"""Plan Contable General Empresarial (PCGE, versión modificada 2019 — vigente
desde el 01/01/2020), catálogo de fábrica del ERP.

**Por qué vive en código y no en configuración.** El resto del módulo evita
cablear cuentas (`regla_asiento`, `parametro_empresa`) porque el plan de
cuentas es decisión de cada empresa. El PCGE no es eso: es el catálogo
**oficial** que el Consejo Normativo de Contabilidad obliga a usar en el
Perú, igual para todas las empresas del grupo y para el contador externo.
Tenerlo acá es lo que evita inventar el número de una cuenta que ya existe
—el problema que este catálogo resuelve—. Lo que sigue siendo configurable
es **qué cuenta usa cada evento** (`regla_asiento`) y qué cuentas la empresa
activa o agrega.

**Cobertura.** Elementos 1 a 7 y 9 completos a nivel de rubro (dos dígitos),
con las divisionarias de tres a cinco dígitos que una operación de
restaurante realmente usa. De los elementos 8 y 0:

- del **8** se siembran solo `87` (participaciones de los trabajadores) y
  `88` (impuesto a la renta), que sí son gasto del ejercicio. Los saldos
  intermediarios de gestión (`80`-`85`) y la determinación del resultado
  (`89`) no se siembran: son cuentas de cierre anual que arma el contador
  externo, y los estados financieros de este módulo calculan el resultado
  directamente de los elementos 6, 7 y 9 sin pasar por `89`;
- el **0** (cuentas de orden) queda fuera: no mueve activo, pasivo ni
  resultado, y hoy ningún proceso del ERP lo alimenta.

Las dos omisiones están anotadas como deuda en `ROADMAP.md`.

**Elemento 9.** El PCGE lo deja de denominación libre. El ERP fija la
convención más difundida en el Perú y la documenta acá para que nadie la
adivine: 91 costo de producción, 94 gastos de administración, 95 gastos de
ventas, 97 gastos financieros.
"""

