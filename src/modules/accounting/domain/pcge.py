#: Índice por código, para resolver una cuenta sin recorrer la tupla.
DENOMINACIONES: dict[str, str] = dict(CUENTAS)


def tipo_de(codigo: str) -> str:
    """Tipo de `cuenta_contable` que le toca a un código del PCGE.

    Se deriva del elemento (primer dígito) y no se declara cuenta por cuenta:
    el PCGE ya ordenó el catálogo por naturaleza, y repetirlo sería una lista
    de 400 líneas que se desincroniza.
    """
    try:
        return TIPO_POR_ELEMENTO[codigo[0]]
    except (IndexError, KeyError) as e:
        raise ValueError(f"código fuera del PCGE: {codigo!r}") from e


def padre_de(codigo: str) -> str | None:
    """Código del padre inmediato dentro del catálogo, o `None` si es rubro.

    El padre es el prefijo más largo que exista en el catálogo, no
    simplemente `codigo[:-1]`: hay divisionarias que saltan un nivel
    (`40111` cuelga de `4011`, `6011` de `601`) y rubros que no cuelgan de
    nada porque su elemento no se siembra completo.
    """
    for largo in range(len(codigo) - 1, 1, -1):
        prefijo = codigo[:largo]
        if prefijo in DENOMINACIONES:
            return prefijo
    return None
